# Embedding cache
# --------------------------------------------------------------------------------------------
class EmbeddingCacheRepo:
    def get_many(self, model: str, hashes: list[str]) -> dict[str, bytes]:
        if not hashes:
            return {}
        out: dict[str, bytes] = {}
        with get_conn() as c:
            for i in range(0, len(hashes), 500):
                batch = hashes[i : i + 500]
                marks = ",".join("?" * len(batch))
                rows = c.execute(
                    f"SELECT text_hash, vector FROM embedding_cache WHERE model = ? AND text_hash IN ({marks})",
                    [model, *batch],
                ).fetchall()
                for r in rows:
                    out[r["text_hash"]] = bytes(r["vector"])
        return out

    def put_many(self, model: str, items: dict[str, bytes]) -> None:
        if not items:
            return
        with get_conn() as c:
            c.executemany(
                "INSERT OR REPLACE INTO embedding_cache(model, text_hash, vector) VALUES (?,?,?)",
                [(model, h, v) for h, v in items.items()],
            )
