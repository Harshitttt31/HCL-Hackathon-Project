class AuditRepo:
    def insert(self, trace_id: str, ts: str, student_id_hash: Optional[str], question_hash: str,
               category: Optional[str], answer_type: Optional[str], latency_ms: int, record: dict) -> None:
        with get_conn() as c:
            c.execute(
                "INSERT OR REPLACE INTO audit_log(trace_id, ts, student_id_hash, question_hash, question_category, "
                "answer_type, latency_ms, record_json) VALUES (?,?,?,?,?,?,?,?)",
                (trace_id, ts, student_id_hash, question_hash, category, answer_type, latency_ms,
                 json.dumps(record, default=str, ensure_ascii=False)),
            )

    def get(self, trace_id: str) -> Optional[dict]:
        with get_conn() as c:
            row = c.execute("SELECT record_json FROM audit_log WHERE trace_id = ?", (trace_id,)).fetchone()
        return json.loads(row["record_json"]) if row else None

    def count(self) -> int:
        with get_conn() as c:
            return int(c.execute("SELECT COUNT(*) FROM audit_log").fetchone()[0])


