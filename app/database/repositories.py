# Rule registry (Annex C)
# --------------------------------------------------------------------------------------------
_RULE_COLS = (
    "rule_id, description, parameter, operator, value, scope_programmes, scope_batches, effective_from, "
    "effective_to, source_doc_id, source_section, unit, attributes, origin, quote, chunk_id, source_page"
)


def _rule_from_row(row: sqlite3.Row) -> RuleRow:
    d = dict(row)
    d["attributes"] = json.loads(d["attributes"]) if d.get("attributes") else None
    d["effective_to"] = d["effective_to"] or None
    return RuleRow(**d)


class RuleRepo:
    def candidates(self, parameter: str) -> list[RuleRow]:
        with get_conn() as c:
            rows = c.execute(
                f"SELECT {_RULE_COLS} FROM rule_registry WHERE parameter = ? ORDER BY effective_from, rule_id",
                (parameter,),
            ).fetchall()
        return [_rule_from_row(r) for r in rows]

    def get(self, rule_id: str) -> Optional[RuleRow]:
        with get_conn() as c:
            row = c.execute(f"SELECT {_RULE_COLS} FROM rule_registry WHERE rule_id = ?", (rule_id,)).fetchone()
        return _rule_from_row(row) if row else None

    def list_all(self) -> list[RuleRow]:
        with get_conn() as c:
            rows = c.execute(f"SELECT {_RULE_COLS} FROM rule_registry ORDER BY parameter, effective_from, rule_id").fetchall()
        return [_rule_from_row(r) for r in rows]

    def parameters(self) -> list[str]:
        with get_conn() as c:
            return [r[0] for r in c.execute("SELECT DISTINCT parameter FROM rule_registry ORDER BY parameter").fetchall()]

    def upsert(self, row: RuleRow, conn: Optional[sqlite3.Connection] = None) -> None:
        sql = (
            f"INSERT INTO rule_registry({_RULE_COLS}, created_at) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?) "
            "ON CONFLICT(rule_id) DO UPDATE SET description=excluded.description, parameter=excluded.parameter, "
            "operator=excluded.operator, value=excluded.value, scope_programmes=excluded.scope_programmes, "
            "scope_batches=excluded.scope_batches, effective_from=excluded.effective_from, effective_to=excluded.effective_to, "
            "source_doc_id=excluded.source_doc_id, source_section=excluded.source_section, unit=excluded.unit, "
            "attributes=excluded.attributes, origin=excluded.origin, quote=excluded.quote, chunk_id=excluded.chunk_id, "
            "source_page=excluded.source_page"
        )
        args = (
            row.rule_id, row.description, row.parameter, row.operator, row.value, row.scope_programmes, row.scope_batches,
            row.effective_from, row.effective_to or None, row.source_doc_id, row.source_section, row.unit,
            json.dumps(row.attributes) if row.attributes else None, row.origin, row.quote, row.chunk_id,
            row.source_page, now_iso(),
        )
        if conn is not None:
            conn.execute(sql, args)
        else:
            with get_conn() as c:
                c.execute(sql, args)

    def delete_extracted_for_doc(self, doc_id: str, conn: Optional[sqlite3.Connection] = None) -> int:
        sql = "DELETE FROM rule_registry WHERE source_doc_id = ? AND origin = 'extracted'"
        if conn is not None:
            return conn.execute(sql, (doc_id,)).rowcount
        with get_conn() as c:
            return c.execute(sql, (doc_id,)).rowcount

    def for_doc(self, doc_id: str) -> list[RuleRow]:
        with get_conn() as c:
            rows = c.execute(
                f"SELECT {_RULE_COLS} FROM rule_registry WHERE source_doc_id = ? ORDER BY rule_id", (doc_id,)
            ).fetchall()
        return [_rule_from_row(r) for r in rows]

    def count(self) -> int:
        with get_conn() as c:
            return int(c.execute("SELECT COUNT(*) FROM rule_registry").fetchone()[0])


# --------------------------------------------------------------------------------------------
# Chunks (SQLite is the system of record for chunk text + metadata; Chroma holds the vectors)
# --------------------------------------------------------------------------------------------
_CHUNK_COLS = (
    "chunk_id, doc_id, ordinal, section_number, section_title, section_path, heading_level, page, kind, text, "
    "embed_text, table_json, references_json, prev_chunk_id, next_chunk_id, content_hash, injection_suspected, "
    "confidence, ocr"
)


def _chunk_from_row(row: sqlite3.Row) -> ChunkRow:
    d = dict(row)
    d["section_path"] = json.loads(d["section_path"] or "[]")
    d["table_json"] = json.loads(d["table_json"]) if d.get("table_json") else None
    d["references"] = json.loads(d.pop("references_json") or "[]")
    d["injection_suspected"] = bool(d["injection_suspected"])
    d["ocr"] = bool(d["ocr"])
    return ChunkRow(**d)


class ChunkRepo:
    def insert_many(self, chunks: Iterable[ChunkRow], conn: Optional[sqlite3.Connection] = None) -> int:
        sql = f"INSERT OR REPLACE INTO chunks({_CHUNK_COLS}) VALUES ({','.join('?' * 19)})"
        data = [
            (
                ch.chunk_id, ch.doc_id, ch.ordinal, ch.section_number, ch.section_title, json.dumps(ch.section_path),
                ch.heading_level, ch.page, ch.kind, ch.text, ch.embed_text,
                json.dumps(ch.table_json) if ch.table_json else None, json.dumps(ch.references), ch.prev_chunk_id,
                ch.next_chunk_id, ch.content_hash, int(ch.injection_suspected), ch.confidence, int(ch.ocr),
            )
            for ch in chunks
        ]
        if conn is not None:
            conn.executemany(sql, data)
        else:
            with get_conn() as c:
                c.executemany(sql, data)
        return len(data)

    def delete_by_doc(self, doc_id: str, conn: Optional[sqlite3.Connection] = None) -> int:
        sql = "DELETE FROM chunks WHERE doc_id = ?"
        if conn is not None:
            return conn.execute(sql, (doc_id,)).rowcount
        with get_conn() as c:
            return c.execute(sql, (doc_id,)).rowcount

    def get(self, chunk_id: str) -> Optional[ChunkRow]:
        with get_conn() as c:
            row = c.execute(f"SELECT {_CHUNK_COLS} FROM chunks WHERE chunk_id = ?", (chunk_id,)).fetchone()
        return _chunk_from_row(row) if row else None

    def get_many(self, chunk_ids: list[str]) -> dict[str, ChunkRow]:
        if not chunk_ids:
            return {}
        out: dict[str, ChunkRow] = {}
        with get_conn() as c:
            for i in range(0, len(chunk_ids), 500):
                batch = chunk_ids[i : i + 500]
                marks = ",".join("?" * len(batch))
                rows = c.execute(f"SELECT {_CHUNK_COLS} FROM chunks WHERE chunk_id IN ({marks})", batch).fetchall()
                for r in rows:
                    ch = _chunk_from_row(r)
                    out[ch.chunk_id] = ch
        return out

    def by_doc(self, doc_id: str) -> list[ChunkRow]:
        with get_conn() as c:
            rows = c.execute(f"SELECT {_CHUNK_COLS} FROM chunks WHERE doc_id = ? ORDER BY ordinal", (doc_id,)).fetchall()
        return [_chunk_from_row(r) for r in rows]

    def all(self) -> list[ChunkRow]:
        with get_conn() as c:
            rows = c.execute(f"SELECT {_CHUNK_COLS} FROM chunks ORDER BY doc_id, ordinal").fetchall()
        return [_chunk_from_row(r) for r in rows]

    def find_by_section(self, doc_id: str, section_number: str) -> list[ChunkRow]:
        """Chunks whose section number equals, or is nested under, the given clause number."""
        like = section_number.replace("%", "").replace("_", "") + ".%"
        with get_conn() as c:
            rows = c.execute(
                f"SELECT {_CHUNK_COLS} FROM chunks WHERE doc_id = ? AND (section_number = ? OR section_number LIKE ?) "
                "ORDER BY ordinal",
                (doc_id, section_number, like),
            ).fetchall()
        return [_chunk_from_row(r) for r in rows]

    def count(self) -> int:
        with get_conn() as c:
            return int(c.execute("SELECT COUNT(*) FROM chunks").fetchone()[0])


