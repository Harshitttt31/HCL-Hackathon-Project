from app.core.clock import now_iso
from app.database.models import (
    AttendanceRow,
    ChunkRow,
    CourseRow,
    ResultRow,
    RuleRow,
    StudentRow,
)
from app.database.sqlite import get_conn


# --------------------------------------------------------------------------------------------
# Students (personal data: always scoped by student_id)
# --------------------------------------------------------------------------------------------
class StudentRepo:
    def get(self, student_id: str) -> Optional[StudentRow]:
        with get_conn() as c:
            row = c.execute(
                "SELECT student_id, full_name, programme, batch_year, current_semester, cgpa, active_backlogs "
                "FROM students WHERE student_id = ?",
                (student_id,),
            ).fetchone()
        return StudentRow(**dict(row)) if row else None

    def upsert(self, row: StudentRow, conn: Optional[sqlite3.Connection] = None) -> None:
        sql = (
            "INSERT INTO students(student_id, full_name, programme, batch_year, current_semester, cgpa, active_backlogs) "
            "VALUES (?,?,?,?,?,?,?) ON CONFLICT(student_id) DO UPDATE SET "
            "full_name=excluded.full_name, programme=excluded.programme, batch_year=excluded.batch_year, "
            "current_semester=excluded.current_semester, cgpa=excluded.cgpa, active_backlogs=excluded.active_backlogs"
        )
        args = (row.student_id, row.full_name, row.programme, row.batch_year, row.current_semester, row.cgpa, row.active_backlogs)
        if conn is not None:
            conn.execute(sql, args)
        else:
            with get_conn() as c:
                c.execute(sql, args)

    def count(self) -> int:
        with get_conn() as c:
            return int(c.execute("SELECT COUNT(*) FROM students").fetchone()[0])

    def identity_lexicon(self) -> dict[str, set[str]]:
        """Names and ids used ONLY to detect references to other people in a question.

        The result is used for pattern matching inside the privacy checker and is never returned
        to a caller or written to logs.
        """
        with get_conn() as c:
            rows = c.execute("SELECT student_id, full_name FROM students").fetchall()
        names: set[str] = set()
        ids: set[str] = set()
        for r in rows:
            ids.add(r["student_id"].upper())
            full = r["full_name"].strip()
            names.add(full.lower())
            for part in full.split():
                if len(part) >= 3:
                    names.add(part.lower())
        return {"ids": ids, "names": names}


