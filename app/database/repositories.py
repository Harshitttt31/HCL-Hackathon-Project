class CourseRepo:
    def get(self, course_code: str) -> Optional[CourseRow]:
        with get_conn() as c:
            row = c.execute(
                "SELECT course_code, course_name, programme, semester, credits FROM courses WHERE course_code = ?",
                (course_code.upper(),),
            ).fetchone()
        return CourseRow(**dict(row)) if row else None

    def list_for_programme(self, programme: Optional[str] = None) -> list[CourseRow]:
        with get_conn() as c:
            if programme:
                rows = c.execute(
                    "SELECT course_code, course_name, programme, semester, credits FROM courses "
                    "WHERE programme = ? ORDER BY semester, course_code",
                    (programme,),
                ).fetchall()
            else:
                rows = c.execute(
                    "SELECT course_code, course_name, programme, semester, credits FROM courses ORDER BY programme, semester, course_code"
                ).fetchall()
        return [CourseRow(**dict(r)) for r in rows]

    def upsert(self, row: CourseRow, conn: Optional[sqlite3.Connection] = None) -> None:
        sql = (
            "INSERT INTO courses(course_code, course_name, programme, semester, credits) VALUES (?,?,?,?,?) "
            "ON CONFLICT(course_code) DO UPDATE SET course_name=excluded.course_name, programme=excluded.programme, "
            "semester=excluded.semester, credits=excluded.credits"
        )
        args = (row.course_code.upper(), row.course_name, row.programme, row.semester, row.credits)
        if conn is not None:
            conn.execute(sql, args)
        else:
            with get_conn() as c:
                c.execute(sql, args)

    def count(self) -> int:
        with get_conn() as c:
            return int(c.execute("SELECT COUNT(*) FROM courses").fetchone()[0])


