"""Allowlisted data access layer.

Every query here is a fixed, parameterised statement. There is NO function that accepts SQL text,
and nothing generated by an LLM ever reaches the database. Student-scoped methods require the
student_id explicitly and always filter on it.
"""
from __future__ import annotations

import json
